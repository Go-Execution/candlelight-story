-- ============================================================================
-- SECURE CUSTOMER ORDER LOOKUP & INVENTORY RPC FUNCTIONS
-- ============================================================================
create or replace function public.lookup_order(p_order_id text, p_email text default null)
returns setof public.orders
language sql
security definer
set search_path = public
as $$
  select *
  from public.orders
  where upper(id) = upper(trim(p_order_id))
    and (
      p_email is null
      or trim(p_email) = ''
      or lower(customer_email) = lower(trim(p_email))
    )
  limit 1;
$$;

grant execute on function public.lookup_order(text, text) to anon, authenticated;

create or replace function public.decrement_product_stock(p_product_id bigint, p_qty integer)
returns void
language sql
security definer
set search_path = public
as $$
  update public.products
  set stock = greatest(0, stock - greatest(0, p_qty)),
      updated_at = now()
  where id = p_product_id;
$$;

grant execute on function public.decrement_product_stock(bigint, integer) to anon, authenticated;

